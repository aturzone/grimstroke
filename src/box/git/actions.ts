export const GIT_ACTIONS: readonly GitAction[] = ROWS.map(
  ([object, verb, scope, weight, needs, takes, en, fa, ru]) => ({
    id: `${object}.${verb}`,
    object,
    verb,
    scope,
    weight,
    needs,
    takes,
    en,
    fa,
    ru,
  }),
);

const BY_ID = new Map(GIT_ACTIONS.map((a) => [a.id, a]));

export function gitAction(id: string): GitAction | undefined {
  return BY_ID.get(id);
}

/** Whether a verb can be done to an object at all: the pairs the model may answer with. */
export function pairOf(object: GitObject, verb: GitVerb): GitAction | undefined {
  return BY_ID.get(`${object}.${verb}`);
}
