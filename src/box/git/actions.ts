/**
 * Everything the box can be asked to do with git, as data: one entry per action, by the object
 * it acts on and the verb it does. The understanding (model.ts), the slot readers (slots.ts), the
 * plan (understand.ts) and the doing (git/do.ts) all read this list, so an action exists once.
 *
 * An action is a verb on an object -- close an issue, merge a pull request, push a branch. The
 * model reads the verb and the object separately and only pairs that are here can be the answer,
 * so "close" said of a pull request is never closing an issue, and a new object or verb learnt
 * from one language's sentences carries to the others.
 *
 * Where an action happens: on the service (GitHub, GitLab, Gitea), on a clone on this machine,
 * or either -- a branch can be made on both, and which one is meant is read from the sentence and
 * from where grimstroke is standing (see understand.ts).
 */

