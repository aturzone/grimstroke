const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * One pattern for a set of stems: each at the start of a word in a spaced script, anywhere in a
 * dense one. Longest first, so "pull request" is found before "pull".
 */
export function stemPattern(stems: readonly string[], dense = false): RegExp | null {
  // Folded as the sentence is (text.ts): ё is е, Arabic kaf is Persian kaf, ZWNJ is a space.
  const list = [...new Set(stems.map((s) => fold(s).toLowerCase()).filter(Boolean))].sort(
    (a, b) => b.length - a.length,
  );
  if (!list.length) return null;
  const body = list.map((s) => escapeRe(s.trimEnd())).join('|');
  return dense ? new RegExp(`(?:${body})`, 'u') : new RegExp(`(?<![\\p{L}\\p{N}])(?:${body})`, 'u');
}

/** Every language's stems for one thing, as one pattern each for spaced and dense scripts. */
export function speechPattern(pick: (s: GitSpeech) => readonly string[] | undefined): RegExp[] {
  const spaced = GIT_SPEECH.filter((s) => !s.dense).flatMap((s) => pick(s) ?? []);
  const dense = GIT_SPEECH.filter((s) => s.dense).flatMap((s) => pick(s) ?? []);
  return [stemPattern(spaced), stemPattern(dense, true)].filter((r): r is RegExp => r !== null);
}
