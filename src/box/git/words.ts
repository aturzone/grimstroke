/**
 * How git is said, language by language: the words for each verb and each object of
 * actions.ts, and the little words around them -- who an issue goes to, which repository, from
 * which branch to which.
 *
 * One entry per language. A word here is a STEM, matched at the start of a word ("close" finds
 * "closed", "закр" finds "закройте", "ببند" finds "ببندش"); a stem with a space in it is a phrase.
 * Chinese and Japanese have no spaces, so theirs are matched anywhere in the line. Lowercase,
 * and Persian with its Arabic letters already folded (text.ts).
 *
 * The model (model.ts) does not depend on this list being complete -- it learns from letters as
 * well -- but every word here is one it can be sure of, and the slot readers (slots.ts) need the
 * little words to find a person, a repository or a branch whatever order the sentence is in.
 */

import type { GitObject, GitVerb } from '@core/box/git/actions.ts';
import { fold } from '@core/box/text.ts';

export interface GitSpeech {
  lang: string;
  /** No spaces between words: matched inside the line. */
  dense?: boolean;
  verbs: Partial<Record<GitVerb, string[]>>;
  objects: Record<GitObject, string[]>;
  /** Before a person an issue is given to: "to sina", "به سینا", "на сину". */
  toPerson: string[];
  /** Before a repository: "in web", "توی web", "в web". */
  inRepo: string[];
  /** Branch from and to: "from fix into main", "از fix به main", "из fix в main". */
  from: string[];
  into: string[];
  /** Said of oneself: "my issues", "assigned to me". */
  mine: string[];
  /** States a list is asked for in. */
  open: string[];
  closed: string[];
  merged: string[];
  all: string[];
  /** On the service rather than here, and here rather than on the service. */
  remoteCue: string[];
  localCue: string[];
  /** Before a label's name: "label bug", "لیبل باگ". */
  labelWord: string[];
  /** Words that are about the thing just talked about: "it", "that one", "همون". */
  that: string[];
}

